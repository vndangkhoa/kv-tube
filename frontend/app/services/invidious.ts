  async getAllAuthHistory(maxPages: number = 20): Promise<any[]> {
    const allVideos: any[] = [];
    const seen = new Set<string>();

    for (let p = 1; p <= maxPages; p++) {
      try {
        const pageItems = await this.getAuthHistory(p);
        if (!Array.isArray(pageItems) || pageItems.length === 0) break;

        let addedThisPage = 0;
        for (const item of pageItems) {
          const id = item.videoId || item.id;
          if (id && !seen.has(id)) {
            seen.add(id);
            allVideos.push(item);
            addedThisPage++;
          }
        }

        if (addedThisPage === 0 || pageItems.length < 5) break;
      } catch (err) {
        console.warn(`[getAllAuthHistory] Error on page ${p}:`, err);
        break;
      }
    }

    return allVideos;
  }

