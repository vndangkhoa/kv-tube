  private static readonly FALLBACK_INSTANCES = [
    'https://yewtu.be',
    'https://invidious.nerdvpn.de',
    'https://invidious.snopyta.org',
    'https://inv.tux.pizza',
  ];

  // Generic Public API fetcher with multi-node resilient fallback
  public async fetchApi<T>(endpoint: string, params: Record<string, any> = {}): Promise<T> {
    const instancesToTry = [
      this.instanceUrl,
      ...InvidiousService.FALLBACK_INSTANCES.filter(i => i !== this.instanceUrl),
    ];

    let lastError: any = null;

    for (const base of instancesToTry) {
      try {
        const url = new URL(`${base}/api/v1${endpoint}`);
        Object.entries(params).forEach(([key, val]) => {
          if (val !== undefined && val !== null && val !== '') {
            url.searchParams.set(key, String(val));
          }
        });

        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 7000);

        const res = await fetch(url.toString(), {
          headers: {
            'Accept': 'application/json',
          },
          signal: controller.signal,
        });

        clearTimeout(timeoutId);

        if (res.ok) {
          return await res.json();
        }
      } catch (err: any) {
        lastError = err;
        continue;
      }
    }

    throw lastError || new Error(`All Invidious instances failed for ${endpoint}`);
  }

  // Generic Authenticated API fetcher
  public async fetchAuthApi<T>(
    endpoint: string,
    options: { method?: string; body?: any; params?: Record<string, any> } = {}
  ): Promise<T> {
    const token = this.getToken();
    const isBrowser = typeof window !== 'undefined';

    // In browser, route through our Next.js API server proxy to avoid CORS and forbidden-header ('Cookie') restrictions
    const baseUrl = isBrowser ? `/api/invidious/api/v1/auth${endpoint}` : `${this.instanceUrl}/api/v1/auth${endpoint}`;
    const url = new URL(baseUrl, isBrowser ? window.location.origin : this.instanceUrl);

    if (options.params) {
      Object.entries(options.params).forEach(([k, v]) => {
        if (v !== undefined && v !== null && v !== '') {
          url.searchParams.set(k, String(v));
        }
      });
    }

    const headers: Record<string, string> = {
      'Accept': 'application/json',
    };

    if (token) {
      const trimmed = token.trim();
      if (isBrowser) {
        headers['x-invidious-token'] = trimmed;
        if (trimmed.startsWith('{')) {
          headers['Authorization'] = `Bearer ${trimmed}`;
        }
      } else {
        if (trimmed.startsWith('{')) {
          headers['Authorization'] = `Bearer ${trimmed}`;
        } else {
          headers['Cookie'] = `SID=${trimmed}`;
        }
      }
    }

    if (options.body) {
      headers['Content-Type'] = 'application/json';
    }

    const res = await fetch(url.toString(), {
      method: options.method || 'GET',
      headers,
      body: options.body ? JSON.stringify(options.body) : undefined,
    });

    if (!res.ok) {
      let errMsg = `Invidious Auth API error (${res.status}): ${res.statusText}`;
      try {
        const errJson = await res.json();
        if (errJson?.error) errMsg = errJson.error;
      } catch {}
      throw new Error(errMsg);
    }

    return res.json();
  }

  // Test token against Invidious authenticated endpoints
  public async testAuthToken(customToken?: string): Promise<{ success: boolean; message: string; details?: any }> {
    const originalToken = this.getToken();
    if (customToken !== undefined) {
      this.setToken(customToken.trim());
    }

    try {
      const activeToken = this.getToken();
      if (!activeToken) {
        return { success: false, message: 'No token provided' };
      }

      // Try fetching subscriptions
      const subs = await this.getAuthSubscriptions();
      return {
        success: true,
        message: `Successfully connected to Invidious! Found ${Array.isArray(subs) ? subs.length : 0} subscriptions.`,
        details: { subscriptionsCount: Array.isArray(subs) ? subs.length : 0 },
      };
    } catch (err: any) {
      return {
        success: false,
        message: err?.message || 'Authentication failed',
      };
    } finally {
      if (customToken !== undefined) {
        this.setToken(originalToken);
      }
    }
  }

