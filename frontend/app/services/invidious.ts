  // Parse any subscriptions format (Invidious JSON, NewPipe JSON, Google Takeout CSV, OPML XML)
  parseSubscriptions(content: string): Array<{ channelId: string; channelName: string; channelAvatar?: string }> {
    const list: Array<{ channelId: string; channelName: string; channelAvatar?: string }> = [];

    // 1. Try JSON formats (Invidious / NewPipe / FreeTube)
    try {
      const parsed = JSON.parse(content);
      if (Array.isArray(parsed)) {
        for (const item of parsed) {
          if (typeof item === 'string' && item.startsWith('UC')) {
            list.push({ channelId: item, channelName: item });
          } else if (item && typeof item === 'object') {
            const id = item.authorId || item.channel_id || item.channelId || item.id || item.url?.split('/').pop() || '';
            const name = item.author || item.channel_name || item.channelName || item.name || item.title || id;
            const avatar = item.authorThumbnails?.[0]?.url || item.avatar || '';
            if (id) list.push({ channelId: id, channelName: name, channelAvatar: avatar });
          }
        }
        if (list.length > 0) return list;
      } else if (parsed && typeof parsed === 'object' && Array.isArray(parsed.subscriptions)) {
        for (const item of parsed.subscriptions) {
          const id = item.url?.split('/').pop() || item.channelId || item.id || '';
          const name = item.name || item.title || id;
          if (id) list.push({ channelId: id, channelName: name });
        }
        if (list.length > 0) return list;
      }
    } catch {}

    // 2. Try Google Takeout CSV (Channel Id,Channel Url,Channel Title)
    const lines = content.split('\n');
    for (const line of lines) {
      if (line.includes('Channel Id') || !line.trim()) continue;
      const parts = line.split(',');
      if (parts.length >= 3 && parts[0].trim().startsWith('UC')) {
        const id = parts[0].trim();
        const name = parts.slice(2).join(',').replace(/^"|"$/g, '').trim();
        list.push({ channelId: id, channelName: name || id });
      }
    }
    if (list.length > 0) return list;

    // 3. Try OPML / XML regex
    const opmlMatches = content.matchAll(/xmlUrl="[^"]*channel_id=([a-zA-Z0-9_-]+)"[^>]*title="([^"]*)"/g);
    for (const match of opmlMatches) {
      if (match[1]) {
        list.push({ channelId: match[1], channelName: match[2] || match[1] });
      }
    }

    return list;
  }
